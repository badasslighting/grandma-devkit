'use strict';
const { FUNCTIONS } = require('./ma2Api');

// Definition files for the Lua language server (sumneko.lua): `---@meta` stubs of the console APIs, so
// Printf, Cmd, Root() and gma.* are known globals with typed parameters and `handle:Method()` completes.
const KEYWORDS = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'goto', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while']);
const IDENT = /^[A-Za-z_]\w*$/;

// HelpLua type words -> LuaLS types. Handles are all the same userdata class, `Obj`.
function luaType(t) {
  const w = String(t || '').trim();
  if (w === 'light_userdata' || w === 'handle') return 'Obj';
  if (w === 'string') return 'string';
  if (w === 'integer' || w === 'int') return 'integer';
  if (w === 'float' || w === 'number') return 'number';
  if (w === 'boolean' || w === 'bool') return 'boolean';
  if (w === 'table') return 'table';
  if (w === 'function' || w === 'lua_function' || w === 'callback') return 'function';
  return 'any';
}

function safeName(name, used) {
  let n = String(name || 'arg').replace(/\W+/g, '_').replace(/^_+|_+$/g, '') || 'arg';
  if (/^\d/.test(n)) n = `p_${n}`;
  if (KEYWORDS.has(n)) n += '_';
  let out = n;
  for (let i = 2; used.has(out); i++) out = `${n}${i}`;
  used.add(out);
  return out;
}

// `type:name` after HelpLua's return colon; anything more complicated is a plain `any` or `table`.
function returnType(returns) {
  const r = String(returns || '').trim();
  if (!r || r === 'nothing') return null;
  const m = /^([a-z_]+):(\w+)$/.exec(r);
  if (m) return { type: luaType(m[1]), name: m[2] };
  if (/^[a-z_]+$/.test(r)) return { type: luaType(r), name: '' };
  if (/^\{|^table\b/.test(r)) return { type: 'table', name: '' };
  return { type: 'any', name: '' };
}

function docBlock(fn, skipFirst) {
  const lines = [`---${fn.signature.replace(/\s+/g, ' ')}`];
  const used = new Set();
  const names = [];
  const params = fn.params.slice(skipFirst ? 1 : 0);
  for (const p of params) {
    const variadic = /\.\.\./.test(p.label) || p.name === '...';
    const name = variadic && p.name === '...' ? null : safeName(p.name, used);
    if (name) {
      // Lua turns a number into a string on the way in, and the console accepts that, so allow it.
      const t = luaType(p.type);
      lines.push(`---@param ${name}${p.optional ? '?' : ''} ${t === 'string' ? 'string|number' : t}`);
      names.push(name);
    }
    if (variadic) {
      lines.push('---@param ... any');
      names.push('...');
    }
  }
  const ret = returnType(fn.returns);
  if (ret) lines.push(`---@return ${ret.type}${ret.name ? ` ${ret.name}` : ''}`);
  return { lines, names };
}

// MA3: HelpLua entries -> globals and `Obj` methods.
function ma3Stubs(api) {
  const out = [
    '---@meta',
    '-- grandMA3 Lua API definitions generated by the grandMA devkit from the console\'s HelpLua list.',
    '-- Regenerate with "grandMA: Set Up Lua Language Server Definitions"; do not edit by hand.',
    '',
    '---@class Obj',
    '---@field [string] any',
    'local Obj = {}',
    '---@alias handle Obj',
    '',
    '---@type table<string, table<string, integer>>',
    'Enums = {}',
    '',
  ];
  for (const fn of api.global) {
    if (!IDENT.test(fn.name)) continue;
    const { lines, names } = docBlock(fn, false);
    out.push(...lines, `function ${fn.name}(${names.join(', ')}) end`, '');
  }
  for (const fn of api.object) {
    if (!IDENT.test(fn.name)) continue;
    const { lines, names } = docBlock(fn, true);
    out.push(...lines, `function Obj:${fn.name}(${names.join(', ')}) end`, '');
  }
  return out.join('\n');
}

// MA2: the curated gma.* list; types come from what the parameters are called.
const MA2_TYPES = { command: 'string', text: 'string', title: 'string', message: 'string', address: 'string', name: 'string', default: 'string', file: 'string', seconds: 'number', interval: 'number', count: 'integer', index: 'integer', from: 'number', to: 'number', callback: 'function', cleanup: 'function', table: 'table' };
const MA2_RETURNS = { nothing: null, boolean: 'boolean', number: 'number', string: 'string', table: 'table', 'string or nil': 'string?', 'true or nil': 'true?', 'handle or nil': 'any', handle: 'any', value: 'any' };

function ma2Stubs() {
  const out = [
    '---@meta',
    '-- grandMA2 Lua API definitions generated by the grandMA devkit from its curated gma.* list.',
    '-- Regenerate with "grandMA: Set Up Lua Language Server Definitions"; do not edit by hand.',
    '',
    '---@class gma',
    'gma = {}',
  ];
  const tables = new Set();
  const need = (path) => {
    const parts = path.split('.');
    for (let i = 2; i <= parts.length; i++) {
      const t = parts.slice(0, i).join('.');
      if (!tables.has(t)) {
        tables.add(t);
        out.push(`${t} = {}`);
      }
    }
  };
  for (const fn of FUNCTIONS) need(fn.path.split('.').slice(0, -1).join('.'));
  out.push('');
  for (const fn of FUNCTIONS) {
    out.push(`---${fn.doc}`);
    const names = [];
    for (const p of fn.params) {
      out.push(p.name === '...' ? '---@param ... any' : `---@param ${p.name}${p.optional ? '?' : ''} ${MA2_TYPES[p.name] || 'any'}`);
      names.push(p.name);
    }
    const r = MA2_RETURNS[fn.returns];
    if (r) out.push(`---@return ${r}`);
    out.push(`function ${fn.path}(${names.join(', ')}) end`, '');
  }
  return out.join('\n');
}

// Adds the stub folder to a .luarc.json (plain JSON or JSON with comments). Returns {text} or {error}.
function mergeLuarc(existing, { libraryDir, runtimeVersion }) {
  let cfg = {};
  if (existing && existing.trim()) {
    try {
      cfg = JSON.parse(existing);
    } catch (_) {
      return { error: 'The existing .luarc.json is not plain JSON (comments?); add the library path and runtime version by hand.' };
    }
  }
  const lib = Array.isArray(cfg['workspace.library']) ? cfg['workspace.library'] : [];
  if (!lib.includes(libraryDir)) lib.push(libraryDir);
  cfg['workspace.library'] = lib;
  if (!cfg['runtime.version']) cfg['runtime.version'] = runtimeVersion;
  if (!cfg.$schema) cfg.$schema = 'https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json';
  return { text: `${JSON.stringify(cfg, null, 2)}\n` };
}

module.exports = { luaType, safeName, returnType, ma3Stubs, ma2Stubs, mergeLuarc };
